/**
 * The app's design tokens come from the web repo's design/tokens.json, the one source for both
 * apps (docs/design-system.md). This script:
 *
 * 1. downloads that file from web's `main`, byte for byte, into src/design/tokens.json;
 * 2. generates src/design/tokens.ts (`color`, `space`, `radius`, `type`), which src/theme.ts
 *    re-exports. DTCG aliases (`{color.page}`) are resolved to the value they point at.
 *
 * `bun run design:tokens` does both. With `--offline` it only regenerates from the committed copy:
 * that is what CI runs, so CI never depends on the web repo.
 */
import { readFile, writeFile } from 'node:fs/promises'

const url = 'https://raw.githubusercontent.com/CampusPulse-ro/web/main/design/tokens.json'
const copy = 'src/design/tokens.json'
const target = 'src/design/tokens.ts'

if (!process.argv.includes('--offline')) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`GET ${url}: HTTP ${response.status}`)
  const text = await response.text()
  JSON.parse(text) // refuse anything that isn't JSON before overwriting the copy
  await writeFile(copy, text)
  console.log(`${copy} <- ${url}`)
}

const tokens = JSON.parse(await readFile(copy, 'utf8'))

/** The group's tokens in file order, skipping `$type`, `$description` and other `$` keys. */
function entries(group) {
  return Object.entries(group).filter(([name]) => !name.startsWith('$'))
}

/** `ink-soft` -> `inkSoft`, the names src/theme.ts has always exported. */
function camel(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
}

/** A DTCG alias (`{color.page}`) is replaced by the value it points at, recursively. */
function resolve(value, where, seen = []) {
  if (typeof value === 'string') {
    const alias = /^\{([^{}]+)\}$/.exec(value)
    if (!alias) return value
    const path = alias[1]
    if (seen.includes(path))
      throw new Error(`${copy}: ${where}: alias loop ${[...seen, path].join(' -> ')}`)
    const [groupName, ...rest] = path.split('.')
    const token = tokens[groupName]?.[rest.join('.')]
    if (!token || !('$value' in token)) throw new Error(`${copy}: ${where}: no token ${path}`)
    return resolve(token.$value, where, [...seen, path])
  }
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, where, seen)]))
  }
  return value
}

function group(name, type) {
  const g = tokens[name]
  if (!g || g.$type !== type) throw new Error(`${copy}: no "${name}" group of $type ${type}`)
  return entries(g)
}

function block(name, pairs) {
  return [`export const ${name} = {`, ...pairs.map(([k, v]) => `  ${k}: ${v},`), '} as const', '']
}

const colors = group('color', 'color').map(([name, token]) => {
  const value = resolve(token.$value, `color.${name}`)
  if (typeof value !== 'string' || !/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value)) {
    throw new Error(`${copy}: color.${name} is not a hex color: ${value}`)
  }
  return [camel(name), `'${value}'`]
})

/** A px value (`'16px'`) as a React Native number (density-independent pixels). */
function px(value, where) {
  const match = typeof value === 'string' ? /^(-?\d+(?:\.\d+)?)px$/.exec(value) : null
  if (!match) throw new Error(`${copy}: ${where} is not a px value: ${value}`)
  return Number(match[1])
}

function pixels(groupName) {
  return group(groupName, 'dimension').map(([name, token]) => [
    camel(name),
    String(px(resolve(token.$value, `${groupName}.${name}`), `${groupName}.${name}`)),
  ])
}

/**
 * The type scale as React Native text styles. `lineHeight` is a ratio in the JSON (DTCG) and dp
 * here, so it is rounded from size x ratio. No `fontFamily`: the app keeps the platform font
 * (`font.sans` is web's CSS stack).
 */
const typeStyles = group('type', 'typography').map(([name, token]) => {
  const where = `type.${name}`
  const t = resolve(token.$value, where)
  const fontSize = px(t.fontSize, `${where}.fontSize`)
  if (typeof t.lineHeight !== 'number')
    throw new Error(`${copy}: ${where}.lineHeight must be a ratio`)
  const style = [
    `fontSize: ${fontSize}`,
    `lineHeight: ${Math.round(fontSize * t.lineHeight)}`,
    `fontWeight: '${t.fontWeight}'`,
    `letterSpacing: ${px(t.letterSpacing ?? '0px', `${where}.letterSpacing`)}`,
  ]
  return [camel(name), `{ ${style.join(', ')} }`]
})

const lines = [
  `// Generated by \`bun run design:tokens\` from ${copy}, a copy of the web repo's design/tokens.json.`,
  '// Do not edit: change the tokens there, then run the script here (docs/design-system.md).',
  '',
  ...block('color', colors),
  ...block('space', pixels('space')),
  ...block('radius', pixels('radius')),
  ...block('type', typeStyles),
]

await writeFile(target, lines.join('\n'))
console.log(`${target} <- ${copy}`)
