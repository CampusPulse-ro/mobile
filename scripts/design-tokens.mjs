/**
 * The app's design tokens come from the web repo's design/tokens.json, the one source for both
 * apps (docs/design-system.md). This script:
 *
 * 1. downloads that file from web's `main`, byte for byte, into src/design/tokens.json;
 * 2. generates src/design/tokens.ts (`color`, `space`, `radius`), which src/theme.ts re-exports.
 *
 * `bun run design:tokens` does both. With `--offline` it only regenerates from the committed copy:
 * that is what CI runs, so CI never depends on the web repo.
 */
import { readFile, writeFile } from 'node:fs/promises'

const url = 'https://raw.githubusercontent.com/CampusPulse-ro/web/main/design/tokens.json'
const copy = 'src/design/tokens.json'
const target = 'src/design/tokens.ts'

if (!process.argv.includes('--offline')) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`GET ${url}: HTTP ${response.status}`)
  const text = await response.text()
  JSON.parse(text) // refuse anything that isn't JSON before overwriting the copy
  await writeFile(copy, text)
  console.log(`${copy} <- ${url}`)
}

const tokens = JSON.parse(await readFile(copy, 'utf8'))

/** The group's tokens in file order, skipping `$type`, `$description` and other `$` keys. */
function entries(group) {
  return Object.entries(group).filter(([name]) => !name.startsWith('$'))
}

/** `ink-soft` -> `inkSoft`, the names src/theme.ts has always exported. */
function camel(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
}

function group(name, type) {
  const g = tokens[name]
  if (!g || g.$type !== type) throw new Error(`${copy}: no "${name}" group of $type ${type}`)
  return entries(g)
}

function block(name, pairs) {
  return [`export const ${name} = {`, ...pairs.map(([k, v]) => `  ${k}: ${v},`), '} as const', '']
}

const colors = group('color', 'color').map(([name, token]) => {
  if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(token.$value)) {
    throw new Error(`${copy}: color.${name} is not a hex color: ${token.$value}`)
  }
  return [camel(name), `'${token.$value}'`]
})

/** A dimension in px, as a React Native number (density-independent pixels). */
function pixels(groupName) {
  return group(groupName, 'dimension').map(([name, token]) => {
    const match = /^(\d+(?:\.\d+)?)px$/.exec(token.$value)
    if (!match) throw new Error(`${copy}: ${groupName}.${name} is not a px value: ${token.$value}`)
    return [camel(name), match[1]]
  })
}

const lines = [
  `// Generated by \`bun run design:tokens\` from ${copy}, a copy of the web repo's design/tokens.json.`,
  '// Do not edit: change the tokens there, then run the script here (docs/design-system.md).',
  '',
  ...block('color', colors),
  ...block('space', pixels('space')),
  ...block('radius', pixels('radius')),
]

await writeFile(target, lines.join('\n'))
console.log(`${target} <- ${copy}`)
